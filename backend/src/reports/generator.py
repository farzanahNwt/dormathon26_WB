"""
LAICIs - Official Audit & Regulatory Report Generator
Formats forensic investigation records into compliance-ready dossiers for:
1. Bank Negara Malaysia (BNM) RMiT Audit Report
2. PDRM CCID Police Report Dossier
3. Executive Board Risk & RM Exposure Summary
"""

import time
from typing import Dict, Any


class ReportGenerator:
    """
    Generates formal forensic reports in Markdown and structured text format.
    """

    @staticmethod
    def generate_bnm_report(scan_record: Dict[str, Any]) -> str:
        scan_id = scan_record.get("scan_id", "SCAN-UNKNOWN")
        timestamp = scan_record.get("timestamp", time.strftime("%Y-%m-%d %H:%M:%S UTC"))
        risk_tier = scan_record.get("risk_tier", "UNKNOWN")
        exposure_rm = scan_record.get("exposure_rm", 0.0)
        prev_rm = scan_record.get("prevention_value_rm", 0.0)
        tools = ", ".join(scan_record.get("tools_invoked", []))
        audit_id = scan_record.get("audit_trail_id", "N/A")
        sig = scan_record.get("verifier_signature", "N/A")

        report = f"""# BANK NEGARA MALAYSIA (BNM) - FRAUD INCIDENT FORENSIC DOSSIER
**Compliance Standard:** BNM Risk Management in Technology (RMiT) / Section 420 Penal Code
**Generated By:** LAICIs (WorkBuddy Autonomous Agent Runtime)
**Date & Time:** {timestamp}
**Dossier Reference:** {scan_id}

---

## 1. EXECUTIVE INCIDENT SUMMARY
- **Incident Status:** INVESTIGATION_COMPLETED
- **Risk Assessment Tier:** {risk_tier}
- **Quantified Exposure (RM):** RM {exposure_rm:,.2f}
- **Loss Prevention Value (RM):** RM {prev_rm:,.2f} (Calculated under BNM formula: 30% of potential loss)
- **Target Segment Evaluated:** {scan_record.get("segment_evaluated", "Individual / Retail Customer")}

---

## 2. FORENSIC EVIDENCE & MODEL VERDICTS
- **Input Evaluated:** {scan_record.get("file_name") or scan_record.get("input_type", "Media/Content")}
- **SHA-256 Hash of Evidence:** `{scan_record.get("file_hash_sha256", "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855")}`
- **Multi-Model Composite Confidence:** {scan_record.get("composite_confidence", 0.0) * 100:.1f}%
- **Tools Invoked Autonomously:** {tools}
- **PyTorch EfficientNetV2-S Classification:** {scan_record.get("predicted_label_name", "N/A")} (AI Prob: {scan_record.get("ai_probability", 0.0) * 100:.1f}%)
- **Error Level Analysis (ELA) Compression Metric:** Tampering Score {scan_record.get("ela_score", 0.0):.3f}
- **Semak Mule CCID Status:** {scan_record.get("semak_mule_status", "Clean / No prior records")}

---

## 3. STATUTORY COMPLIANCE & ESCALATION PROTOCOL
- **Emergency Action:** In accordance with BNM Circular, if funds were transferred within the past 24 hours, contact **National Scam Response Centre (NSRC) at 997** immediately.
- **Police Investigation:** Submit this dossier to the nearest Balai Polis or PDRM CCID Infoline at 03-2610 1599.
- **Telco & Web Takedown:** Lodge incident report with MCMC Aduan (aduan.mcmc.gov.my) to request emergency DNS blocklist.

---

## 4. TAMPER-PROOF AUDIT INTEGRITY RECORD
- **Audit ID:** `{audit_id}`
- **Cryptographic Verifier Signature:** `{sig}`
- **Integrity Guarantee:** Immutable SHA-256 hash chaining under LAICIs governance.

*End of Formal Report.*
"""
        return report

    @staticmethod
    def generate_pdrm_dossier(scan_record: Dict[str, Any]) -> str:
        scan_id = scan_record.get("scan_id", "N/A")
        return f"""POLIS DIRAJA MALAYSIA (PDRM) - JABATAN SIASATAN JENAYAH KOMERSIL (JSJK)
LAPORAN TEKNIKAL FORENSIK DIGITAL LAICIs
=============================================================================
No Rujukan Kes: {scan_id}
Tarikh/Masa: {scan_record.get("timestamp", "N/A")}
Kategori: Siasatan Media Sintetik / Penipuan Siber (Seksyen 420 Kanun Keseksaan)

1. MAKLUMAT EKSPLORASI TEKNIKAL
- Jenis Bahan Bukti: {scan_record.get("input_type", "Media/Teks")}
- Nilai Hash SHA-256: {scan_record.get("file_hash_sha256", "N/A")}
- Tahap Keyakinan Sintetik (AI): {scan_record.get("composite_confidence", 0.0) * 100:.1f}%
- Anggaran Kerugian (RM): RM {scan_record.get("exposure_rm", 0.0):,.2f}

2. KEPUTUSAN SEMAK MULE CCID
- Status Semakan: {scan_record.get("semak_mule_status", "Tiada rekod lampau dikesan")}

3. TINDAKAN DISYORKAN PEGAWAI PENYIASAT
- Bekukan akaun bank penerima melalui NSRC (997) di bawah Seksyen 435 KPJ.
- Mohon sekatan telekomunikasi melalui MCMC di bawah Akta 588 Seksyen 211/233.
- Rakam percakapan pengadu dan rampas peranti untuk pemeriksaan makmal forensik.

Disahkan oleh: LAICIs / WorkBuddy Agent Core
Integriti Audit: {scan_record.get("verifier_signature", "N/A")[:32]}...
=============================================================================
"""
